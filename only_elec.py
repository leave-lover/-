# ============================================================================
# 构建直流潮流矩阵
# ============================================================================

def makeBdc(baseMVA, bus, branch):
    nb = len(bus)
    nl = len(branch)
    
    b = 1.0 / branch[:, BR_X]
    tap = np.ones(nl)
    tap_idx = branch[:, BR_RATIO] != 0
    tap[tap_idx] = branch[tap_idx, BR_RATIO]
    b = b / tap
    
    f = branch[:, F_BUS].astype(int)
    t = branch[:, T_BUS].astype(int)
    
    Bf = np.zeros((nl, nb))
    for i in range(nl):
        Bf[i, f[i]] = b[i]
        Bf[i, t[i]] = -b[i]
    
    Cft = np.zeros((nl, nb))
    for i in range(nl):
        Cft[i, f[i]] = 1
        Cft[i, t[i]] = -1
    
    Bbus = Cft.T @ Bf
    
    return Bbus, Bf

